# Column type reconcile (WS5/B-H9): table models must render the SAME DDL the
# hand-written migrations created, so `alembic check` stays clean and future
# migrations can be autogenerated. That means timezone-aware timestamps
# everywhere and enum columns as plain VARCHAR (SQLAlchemy stores enum NAMES,
# e.g. "DRAFT" — native_enum=False + length matches the migrations exactly).
_AWARE_DATETIME = sa.DateTime(timezone=True)


class ExpenseStatus(str, PyEnum):
    """Status lifecycle for expenses."""

    DRAFT = "draft"  # Initial state when created
    PENDING_CONFIRMATION = "pending_confirmation"  # Splits assigned, awaiting confirms
    CONFIRMED = "confirmed"  # All members confirmed
    SETTLED = "settled"  # Debts paid off


class SplitStatus(str, PyEnum):
    """Status for individual expense splits."""

    PENDING = "pending"
    CONFIRMED = "confirmed"
    SETTLED = "settled"


class SettlementClaimStatus(str, PyEnum):
    """Status lifecycle for settlement claims."""

    PENDING = "pending"  # User marked as paid, awaiting owner confirmation
    CONFIRMED = "confirmed"  # Owner confirmed the payment
    REJECTED = "rejected"  # Owner rejected the claim


# WS6 confirmation policy: a pending settlement claim auto-confirms after this
# many hours — the owner's dispute window. Silence is consent (S1-W3).
SETTLEMENT_AUTO_CONFIRM_HOURS = 72

# WS6 strict mode: in non-strict groups (the default), an expense awaiting
# confirmation auto-confirms this many days after its splits were assigned.
# Members can still confirm early or reject within the window.
EXPENSE_AUTO_CONFIRM_DAYS = 3


